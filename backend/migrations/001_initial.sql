-- One safe metadata row per authenticated, structurally valid chat request.
-- external_identity_id + integration_id + user_id are a composite FK so audit
-- cannot claim a user/integration pair that was never mapped. Chat ID, prompts,
-- output, source values, replacements, offsets, hashes, and raw exceptions are
-- deliberately absent. The policy FK is the immutable request-start snapshot.
CREATE TABLE audit_events (
    id                  uuid PRIMARY KEY,
    request_id          uuid NOT NULL UNIQUE,
    occurred_at         timestamptz NOT NULL DEFAULT now(),
    external_identity_id uuid NOT NULL,
    integration_id      uuid NOT NULL,
    user_id             uuid NOT NULL,
    policy_version_id   uuid NOT NULL REFERENCES policy_versions(id) ON DELETE RESTRICT,
    provider_config_revision bigint NOT NULL,
    provider_label      text NOT NULL,
    state               audit_state NOT NULL,
    decision            policy_action,
    model               text,
    stream              boolean NOT NULL DEFAULT false,
    output_chunks_forwarded integer NOT NULL DEFAULT 0,
    request_bytes       integer NOT NULL,
    message_count       smallint NOT NULL,
    duration_ms         integer,
    first_byte_ms       integer,
    provider_http_status smallint,
    safe_error_code     safe_error_code,
    outcome_deadline_at timestamptz,
    CONSTRAINT audit_identity_scope_fk
        FOREIGN KEY (external_identity_id, integration_id, user_id)
        REFERENCES external_identities (id, integration_id, user_id) ON DELETE RESTRICT,
    CONSTRAINT audit_request_bytes_nonnegative CHECK (request_bytes >= 0),
    CONSTRAINT audit_output_chunks_nonnegative CHECK (output_chunks_forwarded >= 0),
    CONSTRAINT audit_nonstream_has_no_output_chunks CHECK (stream OR output_chunks_forwarded = 0),
    CONSTRAINT audit_message_count_bounds CHECK (message_count BETWEEN 1 AND 100),
    CONSTRAINT audit_duration_nonnegative CHECK (duration_ms IS NULL OR duration_ms >= 0),
    CONSTRAINT audit_first_byte_nonnegative CHECK (first_byte_ms IS NULL OR first_byte_ms >= 0),
    CONSTRAINT audit_provider_status_range CHECK (provider_http_status IS NULL OR provider_http_status BETWEEN 100 AND 599),
    CONSTRAINT audit_model_bounded CHECK (model IS NULL OR length(model) BETWEEN 1 AND 128),
    CONSTRAINT audit_event_state_is_final CHECK (state NOT IN ('received', 'detected')),
    CONSTRAINT audit_partial_requires_forwarded_provider_chunk CHECK (
        state <> 'partial' OR (
            output_chunks_forwarded > 0
            AND safe_error_code IS NOT NULL
            AND safe_error_code IN ('provider_error', 'provider_timeout')
        )
    ),
    CONSTRAINT audit_provider_snapshot CHECK (
        provider_config_revision > 0 AND length(provider_label) BETWEEN 1 AND 128
    ),
    CONSTRAINT audit_outcome_deadline_policy CHECK (
        outcome_deadline_at IS NULL OR decision IN ('ALLOW', 'MASK')
    ),
    CONSTRAINT forwarding_intent_requires_deadline CHECK (
        state <> 'forwarding_intent' OR outcome_deadline_at IS NOT NULL
    ),
    CONSTRAINT audit_error_terminal CHECK (
        (safe_error_code IS NULL) OR state IN (
            'detector_error', 'rejected', 'partial', 'provider_error', 'client_cancelled', 'unknown'
        )
    )
);
CREATE INDEX audit_events_time_idx ON audit_events (occurred_at DESC, id DESC);
CREATE INDEX audit_events_user_time_idx ON audit_events (user_id, occurred_at DESC);
CREATE INDEX audit_events_integration_time_idx ON audit_events (integration_id, occurred_at DESC);
CREATE INDEX audit_events_state_time_idx ON audit_events (state, occurred_at DESC);

-- Application-managed append-only transition history. Application transactions
-- append one row and update audit_events.state together. Retention deletes the
-- parent event, which cascades to state history and summaries. Direct UPDATE/
-- DELETE protection for child rows is an application/database-role contract,
-- not enforced by a trigger in this reference DDL.
CREATE TABLE audit_event_states (
    audit_event_id  uuid NOT NULL REFERENCES audit_events(id) ON DELETE CASCADE,
    sequence        smallint NOT NULL,
    state           audit_state NOT NULL,
    occurred_at     timestamptz NOT NULL DEFAULT now(),
    safe_error_code safe_error_code,
    PRIMARY KEY (audit_event_id, sequence),
    CONSTRAINT audit_state_sequence_positive CHECK (sequence > 0),
    CONSTRAINT audit_state_error_terminal CHECK (
        safe_error_code IS NULL OR state IN (
            'detector_error', 'rejected', 'partial', 'provider_error', 'client_cancelled', 'unknown'
        )
    )
);

-- Counts only. Never add source text, offsets, replacement strings, stable
-- value fingerprints, request snippets, or generic JSON metadata here.
CREATE TABLE audit_findings (
    audit_event_id  uuid NOT NULL REFERENCES audit_events(id) ON DELETE CASCADE,
    category        entity_category NOT NULL,
    action          policy_action NOT NULL,
    finding_count   integer NOT NULL,
    PRIMARY KEY (audit_event_id, category, action),
    CONSTRAINT audit_finding_count_positive CHECK (finding_count > 0)
);
CREATE INDEX audit_findings_category_idx ON audit_findings (category, action);

CREATE FUNCTION guard_admin_credential_role() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM users WHERE id = NEW.user_id AND role = 'admin'
    ) THEN
        RAISE EXCEPTION 'admin credential requires an administrator user';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER admin_credential_role_guard
    BEFORE INSERT OR UPDATE ON admin_credentials
    FOR EACH ROW EXECUTE FUNCTION guard_admin_credential_role();

CREATE FUNCTION guard_policy_version_mutation() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    category_count integer;
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.status <> 'draft' THEN
            RAISE EXCEPTION 'policy version must be created as a draft';
        END IF;
        RETURN NEW;
    END IF;
    IF OLD.status = 'published' THEN
        RAISE EXCEPTION 'published policy versions are immutable';
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    IF NEW.status = 'published' THEN
        SELECT count(*) INTO category_count
          FROM policy_rules WHERE policy_version_id = NEW.id;
        IF category_count <> 7 THEN
            RAISE EXCEPTION 'published policy must define all seven categories';
        END IF;
        IF EXISTS (
            SELECT 1
              FROM policy_dictionaries pd
              JOIN dictionary_versions dv ON dv.id = pd.dictionary_version_id
             WHERE pd.policy_version_id = NEW.id AND dv.status <> 'published'
        ) THEN
            RAISE EXCEPTION 'published policy can only reference published dictionaries';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER policy_version_immutable_guard
    BEFORE INSERT OR UPDATE OR DELETE ON policy_versions
    FOR EACH ROW EXECUTE FUNCTION guard_policy_version_mutation();

CREATE FUNCTION guard_policy_rule_mutation() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    target_policy_id uuid;
    target_status version_status;
BEGIN
    FOR target_policy_id IN
        SELECT DISTINCT changed.policy_version_id
          FROM (VALUES
              (CASE WHEN TG_OP IN ('UPDATE', 'DELETE') THEN OLD.policy_version_id END),
              (CASE WHEN TG_OP IN ('INSERT', 'UPDATE') THEN NEW.policy_version_id END)
          ) AS changed(policy_version_id)
         WHERE changed.policy_version_id IS NOT NULL
         ORDER BY changed.policy_version_id
    LOOP
        SELECT status INTO target_status
          FROM policy_versions WHERE id = target_policy_id FOR UPDATE;
        IF FOUND AND target_status = 'published' THEN
            RAISE EXCEPTION 'rules of a published policy version are immutable';
        END IF;
    END LOOP;
    IF TG_OP = 'DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END;
$$;
CREATE TRIGGER policy_rule_immutable_guard
    BEFORE INSERT OR UPDATE OR DELETE ON policy_rules
    FOR EACH ROW EXECUTE FUNCTION guard_policy_rule_mutation();

CREATE FUNCTION guard_policy_dictionary_mutation() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    target_policy_id uuid;
    target_dictionary_id uuid;
    target_status version_status;
BEGIN
    FOR target_policy_id IN
        SELECT DISTINCT changed.policy_version_id
          FROM (VALUES
              (CASE WHEN TG_OP IN ('UPDATE', 'DELETE') THEN OLD.policy_version_id END),
              (CASE WHEN TG_OP IN ('INSERT', 'UPDATE') THEN NEW.policy_version_id END)
          ) AS changed(policy_version_id)
         WHERE changed.policy_version_id IS NOT NULL
         ORDER BY changed.policy_version_id
    LOOP
        SELECT status INTO target_status
          FROM policy_versions WHERE id = target_policy_id FOR UPDATE;
        IF FOUND AND target_status = 'published' THEN
            RAISE EXCEPTION 'dictionary links of a published policy version are immutable';
        END IF;
    END LOOP;
    FOR target_dictionary_id IN
        SELECT DISTINCT changed.dictionary_version_id
          FROM (VALUES
              (CASE WHEN TG_OP IN ('UPDATE', 'DELETE') THEN OLD.dictionary_version_id END),
              (CASE WHEN TG_OP IN ('INSERT', 'UPDATE') THEN NEW.dictionary_version_id END)
          ) AS changed(dictionary_version_id)
         WHERE changed.dictionary_version_id IS NOT NULL
         ORDER BY changed.dictionary_version_id
    LOOP
        SELECT status INTO target_status
          FROM dictionary_versions WHERE id = target_dictionary_id FOR UPDATE;
        IF FOUND AND TG_OP <> 'DELETE' AND TG_OP IN ('INSERT', 'UPDATE')
           AND target_dictionary_id = NEW.dictionary_version_id
           AND target_status <> 'published' THEN
            RAISE EXCEPTION 'policy drafts may only reference published dictionaries';
        END IF;
    END LOOP;
    IF TG_OP = 'DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END;
$$;
CREATE TRIGGER policy_dictionary_immutable_guard
    BEFORE INSERT OR UPDATE OR DELETE ON policy_dictionaries
    FOR EACH ROW EXECUTE FUNCTION guard_policy_dictionary_mutation();

