-- Reference PostgreSQL DDL for the AI gateway design.
-- This file is a design artifact. It has not been run against a database.
-- Target: PostgreSQL 15+; application migrations should preserve these invariants.

CREATE TYPE account_role AS ENUM ('admin', 'user');
CREATE TYPE version_status AS ENUM ('draft', 'published');
CREATE TYPE entity_category AS ENUM (
    'API_KEY', 'ACCESS_TOKEN', 'JWT', 'EMAIL', 'PHONE', 'IP_ADDRESS', 'INTERNAL_HOSTNAME'
);
CREATE TYPE policy_action AS ENUM ('ALLOW', 'MASK', 'BLOCK');
CREATE TYPE audit_state AS ENUM (
    'received', 'detected', 'blocked', 'detector_error', 'rejected',
    'forwarding_intent', 'completed', 'partial', 'provider_error', 'client_cancelled', 'unknown'
);
CREATE TYPE safe_error_code AS ENUM (
    'unsupported_request_field', 'invalid_request', 'invalid_model',
    'conversation_scope_required', 'detector_timeout', 'detector_failure',
    'provider_error', 'provider_timeout',
    'client_cancelled', 'client_disconnected', 'unknown_outcome'
);

CREATE TABLE users (
    id              uuid PRIMARY KEY,
    username        text NOT NULL UNIQUE,
    display_name    text NOT NULL,
    role            account_role NOT NULL,
    enabled         boolean NOT NULL DEFAULT true,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT users_username_nonempty CHECK (length(username) BETWEEN 1 AND 128),
    CONSTRAINT users_display_name_nonempty CHECK (length(display_name) BETWEEN 1 AND 200),
    CONSTRAINT users_username_normalized CHECK (
        username = lower(username) AND username ~ '^[a-z0-9._@+-]+$'
    )
);

-- Only local administrators receive credentials. The encoded Argon2id value
-- includes algorithm version, cost parameters, random salt, and password hash.
CREATE TABLE admin_credentials (
    user_id         uuid PRIMARY KEY REFERENCES users(id) ON DELETE RESTRICT,
    password_hash   text NOT NULL,
    changed_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT admin_credentials_argon2id CHECK (password_hash LIKE '$argon2id$%')
);

-- Session and CSRF token values are generated by the application and only
-- their SHA-256 digests are stored. Password reset or role change revokes rows.
-- CSRF = base64url(HMAC-SHA256(dedicated deployment CSRF key,
-- framed('gateway-csrf-v1', raw session cookie))). Login/auth-me recompute the
-- same token, preserving reload/multi-tab use. CSRF-key rotation revokes all
-- sessions. Initial session budgets: absolute 8h, idle 30m (application checked).
CREATE TABLE admin_sessions (
    id                  uuid PRIMARY KEY,
    user_id             uuid NOT NULL REFERENCES admin_credentials(user_id) ON DELETE CASCADE,
    session_token_hash  bytea NOT NULL UNIQUE,
    csrf_token_hash     bytea NOT NULL,
    created_at          timestamptz NOT NULL DEFAULT now(),
    last_seen_at        timestamptz NOT NULL DEFAULT now(),
    expires_at          timestamptz NOT NULL,
    revoked_at          timestamptz,
    CONSTRAINT admin_sessions_hash_lengths CHECK (
        octet_length(session_token_hash) = 32 AND octet_length(csrf_token_hash) = 32
    ),
    CONSTRAINT admin_sessions_expiry CHECK (expires_at > created_at)
);
CREATE INDEX admin_sessions_user_active_idx
    ON admin_sessions (user_id, expires_at) WHERE revoked_at IS NULL;

-- One installation-level client integration. The integration bearer is high
-- entropy and stored as a digest; the JWT HMAC secret is resolved from an
-- allowlisted deployment secret reference and is never stored here.
CREATE TABLE client_integrations (
    id              uuid PRIMARY KEY,
    name            text NOT NULL,
    enabled         boolean NOT NULL DEFAULT true,
    bearer_key_hash bytea NOT NULL UNIQUE,
    trusted_identity_settings_singleton boolean NOT NULL DEFAULT true,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT integration_name_nonempty CHECK (length(name) BETWEEN 1 AND 128),
    CONSTRAINT integration_bearer_hash_length CHECK (octet_length(bearer_key_hash) = 32)
);

-- Open WebUI v0.11.4 signs its user identity JWT with a single instance-wide
-- HS256 key. This key is distinct from WEBUI_SECRET_KEY and comes from an
-- allowlisted deployment secret reference; it is shared by all trusted ingress
-- connections for this Open WebUI instance, never selected per connection.
CREATE TABLE trusted_identity_settings (
    singleton                 boolean PRIMARY KEY DEFAULT true CHECK (singleton),
    jwt_issuer                text NOT NULL DEFAULT 'open-webui',
    jwt_algorithm             text NOT NULL DEFAULT 'HS256',
    jwt_secret_ref            text NOT NULL,
    max_token_lifetime_seconds integer NOT NULL DEFAULT 300,
    clock_skew_seconds        integer NOT NULL DEFAULT 60,
    updated_at                timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT trusted_jwt_issuer_fixed CHECK (jwt_issuer = 'open-webui'),
    CONSTRAINT trusted_jwt_algorithm_fixed CHECK (jwt_algorithm = 'HS256'),
    CONSTRAINT trusted_jwt_secret_ref_name CHECK (jwt_secret_ref ~ '^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$'),
    CONSTRAINT trusted_token_lifetime_bounds CHECK (max_token_lifetime_seconds BETWEEN 60 AND 300),
    CONSTRAINT trusted_clock_skew_bounds CHECK (clock_skew_seconds BETWEEN 0 AND 60)
);
ALTER TABLE client_integrations
    ADD CONSTRAINT client_integration_trust_settings_fk
    FOREIGN KEY (trusted_identity_settings_singleton)
    REFERENCES trusted_identity_settings (singleton) ON DELETE RESTRICT;

-- A subject is unique within an integration. Revocation is soft so historical
-- audit rows can retain a valid scoped foreign key without retaining the chat ID.
CREATE TABLE external_identities (
    id                  uuid PRIMARY KEY,
    integration_id      uuid NOT NULL REFERENCES client_integrations(id) ON DELETE RESTRICT,
    user_id             uuid NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    external_subject    text NOT NULL,
    created_at          timestamptz NOT NULL DEFAULT now(),
    revoked_at          timestamptz,
    CONSTRAINT external_subject_nonempty CHECK (length(external_subject) BETWEEN 1 AND 255),
    CONSTRAINT external_identity_scope_tuple UNIQUE (id, integration_id, user_id)
);
CREATE UNIQUE INDEX external_identity_active_subject_uq
    ON external_identities (integration_id, external_subject)
    WHERE revoked_at IS NULL;
CREATE INDEX external_identities_user_idx ON external_identities (user_id, integration_id);

-- A detector profile version identifies an immutable deployed detector bundle.
-- The actual recognizer configuration is packaged with the application; this
-- table is the version anchor snapshotted by policy versions and audit rows.
CREATE TABLE detector_profile_versions (
    id              uuid PRIMARY KEY,
    profile_name    text NOT NULL,
    version         integer NOT NULL,
    bundle_checksum text NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT detector_profile_name_nonempty CHECK (length(profile_name) BETWEEN 1 AND 128),
    CONSTRAINT detector_profile_version_positive CHECK (version > 0),
    CONSTRAINT detector_bundle_checksum CHECK (bundle_checksum ~ '^[A-Fa-f0-9]{64}$'),
    CONSTRAINT detector_profile_version_unique UNIQUE (profile_name, version)
);

CREATE TABLE policy_versions (
    id                  uuid PRIMARY KEY,
    version             integer NOT NULL UNIQUE,
    status              version_status NOT NULL DEFAULT 'draft',
    based_on_id         uuid REFERENCES policy_versions(id) ON DELETE RESTRICT,
    detector_profile_id uuid NOT NULL REFERENCES detector_profile_versions(id) ON DELETE RESTRICT,
    created_by_user_id  uuid NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at          timestamptz NOT NULL DEFAULT now(),
    published_by_user_id uuid REFERENCES users(id) ON DELETE RESTRICT,
    published_at        timestamptz,
    CONSTRAINT policy_version_positive CHECK (version > 0),
    CONSTRAINT policy_publish_fields CHECK (
        (status = 'draft' AND published_at IS NULL AND published_by_user_id IS NULL)
        OR (status = 'published' AND published_at IS NOT NULL AND published_by_user_id IS NOT NULL)
    )
);

CREATE TABLE policy_rules (
    policy_version_id uuid NOT NULL REFERENCES policy_versions(id) ON DELETE CASCADE,
    category          entity_category NOT NULL,
    action            policy_action NOT NULL,
    PRIMARY KEY (policy_version_id, category)
);

CREATE TABLE dictionary_versions (
    id                  uuid PRIMARY KEY,
    name                text NOT NULL,
    version             integer NOT NULL,
    status              version_status NOT NULL DEFAULT 'draft',
    created_by_user_id  uuid NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at          timestamptz NOT NULL DEFAULT now(),
    published_by_user_id uuid REFERENCES users(id) ON DELETE RESTRICT,
    published_at        timestamptz,
    CONSTRAINT dictionary_name_nonempty CHECK (length(name) BETWEEN 1 AND 128),
    CONSTRAINT dictionary_version_positive CHECK (version > 0),
    CONSTRAINT dictionary_name_version_unique UNIQUE (name, version),
    CONSTRAINT dictionary_id_version_unique UNIQUE (id, version),
    CONSTRAINT dictionary_publish_fields CHECK (
        (status = 'draft' AND published_at IS NULL AND published_by_user_id IS NULL)
        OR (status = 'published' AND published_at IS NOT NULL AND published_by_user_id IS NOT NULL)
    )
);

-- Corporate terms are intentionally stored as values because the detector must
-- match them. Limit read access to the service/admin plane; never copy them to
-- audit data or diagnostics. At-rest encryption is a deployment requirement.
CREATE TABLE dictionary_entries (
    id                  uuid PRIMARY KEY,
    dictionary_version_id uuid NOT NULL REFERENCES dictionary_versions(id) ON DELETE CASCADE,
    category            entity_category NOT NULL,
    entry_value         text NOT NULL,
    created_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT dictionary_entry_nonempty CHECK (length(entry_value) BETWEEN 1 AND 2048),
    CONSTRAINT dictionary_entry_unique UNIQUE (dictionary_version_id, category, entry_value)
);
CREATE INDEX dictionary_entries_lookup_idx
    ON dictionary_entries (dictionary_version_id, category);

CREATE TABLE policy_dictionaries (
    policy_version_id       uuid NOT NULL REFERENCES policy_versions(id) ON DELETE CASCADE,
    dictionary_version_id   uuid NOT NULL REFERENCES dictionary_versions(id) ON DELETE RESTRICT,
    PRIMARY KEY (policy_version_id, dictionary_version_id)
);

-- Exactly one active pointer per installation. Writers compare revision in a
-- transaction (If-Match/ETag); requests keep the version read at request start.
CREATE TABLE active_policy (
    singleton       boolean PRIMARY KEY DEFAULT true CHECK (singleton),
    policy_version_id uuid NOT NULL UNIQUE REFERENCES policy_versions(id) ON DELETE RESTRICT,
    revision        bigint NOT NULL DEFAULT 1 CHECK (revision > 0),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    updated_by_user_id uuid NOT NULL REFERENCES users(id) ON DELETE RESTRICT
);

-- Every active pointer revision is retained. Reverting to an older policy is a
-- new activation row/revision, so the former active value is never overwritten.
CREATE TABLE policy_activations (
    revision            bigint PRIMARY KEY CHECK (revision > 0),
    policy_version_id   uuid NOT NULL REFERENCES policy_versions(id) ON DELETE RESTRICT,
    actor_user_id       uuid NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    occurred_at         timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE active_policy
    ADD CONSTRAINT active_policy_revision_history_fk
    FOREIGN KEY (revision) REFERENCES policy_activations (revision)
    DEFERRABLE INITIALLY DEFERRED;

