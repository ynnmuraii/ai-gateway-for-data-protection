CREATE FUNCTION guard_active_policy_target() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM policy_versions
         WHERE id = NEW.policy_version_id AND status = 'published'
    ) THEN
        RAISE EXCEPTION 'active policy must reference a published policy version';
    END IF;
    IF TG_OP = 'UPDATE' AND NEW.revision <> OLD.revision + 1 THEN
        RAISE EXCEPTION 'active policy revision must increase by exactly one';
    END IF;
    IF TG_OP = 'INSERT' AND NEW.revision <> 1 THEN
        RAISE EXCEPTION 'initial active policy revision must be one';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER active_policy_target_guard
    BEFORE INSERT OR UPDATE ON active_policy
