CREATE FUNCTION record_policy_activation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO policy_activations (revision, policy_version_id, actor_user_id)
    VALUES (NEW.revision, NEW.policy_version_id, NEW.updated_by_user_id);
    RETURN NEW;
END;
$$;
CREATE TRIGGER active_policy_history_append
    AFTER INSERT OR UPDATE ON active_policy
    FOR EACH ROW EXECUTE FUNCTION record_policy_activation();

CREATE FUNCTION guard_policy_activation_immutable() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'policy activation history is append-only';
END;
$$;
CREATE TRIGGER policy_activation_immutable_guard
    BEFORE UPDATE OR DELETE ON policy_activations
    FOR EACH ROW EXECUTE FUNCTION guard_policy_activation_immutable();

CREATE FUNCTION guard_active_policy_delete() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'the active policy pointer cannot be deleted';
END;
$$;
CREATE TRIGGER active_policy_delete_guard
    BEFORE DELETE ON active_policy
    FOR EACH ROW EXECUTE FUNCTION guard_active_policy_delete();

CREATE FUNCTION guard_provider_config_revision() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' AND NEW.revision <> 1 THEN
        RAISE EXCEPTION 'initial provider config revision must be one';
    END IF;
    IF TG_OP = 'UPDATE' AND NEW.revision <> OLD.revision + 1 THEN
        RAISE EXCEPTION 'provider config revision must increase by exactly one';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER provider_config_revision_guard
    BEFORE INSERT OR UPDATE ON provider_config
    FOR EACH ROW EXECUTE FUNCTION guard_provider_config_revision();

-- Additional guarantees are transaction/application responsibilities:
-- * read policy and provider_config rows once per request and keep both
--   snapshots through completion; audit the provider revision before egress;
-- * commit audit_events.state='forwarding_intent' and its state-history row
--   before any provider network call;
-- * append audit_event_states and update audit_events in the same transaction;
--   map abandoned/interrupted states to unknown during reconciliation;
-- * restrict application DB credentials and admin endpoints. Dictionary entry
--   values are sensitive; encrypt storage/backups at rest and omit values from
--   all logs and audit responses;
-- * validate a deployment secret reference against the configured allowlist;
--   database constraints only validate its name shape, not its resolution;
-- * seed singleton configuration rows and a complete published initial policy
--   during installation bootstrap.
